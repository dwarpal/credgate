"""Write a synthetic call-centre table as Parquet, for the large-data examples.

Every name and identifier is generated by credgate's synthetic generator;
no real personal data is used.

Requires: pip install 'credgate[arrow]'
Run:      python examples/python/make_synthetic_calls.py [rows] [path]
          (defaults: 100000 rows, examples/data/calls.parquet)
"""

import random
import sys
from pathlib import Path

import credgate
import pyarrow as pa
import pyarrow.parquet as pq

ROWS = int(sys.argv[1]) if len(sys.argv) > 1 else 100_000
PATH = Path(sys.argv[2] if len(sys.argv) > 2 else "examples/data/calls.parquet")

TEMPLATES = [
    "Shri {name} called about a failed UPI payment to {upi_id}.",
    "Customer asked to update mobile to {mobile}; PAN {pan} verified.",
    "Name: {name}. Wants the EMI date moved; account {bank_account}, IFSC {ifsc}.",
    "Branch hours query, no customer details given.",
    "Complaint about app login; email on file {email}.",
    "{name} ji ka Aadhaar {aadhaar} se e-KYC karna hai.",
]


def main() -> None:
    rng = random.Random(42)
    records = credgate.synth_indian_pii(2_000, seed=42)
    notes, pans, mobiles, amounts = [], [], [], []
    for i in range(ROWS):
        r = records[i % len(records)]
        notes.append(rng.choice(TEMPLATES).format(**r))
        pans.append(r["pan"])
        mobiles.append(int(r["mobile"]))
        amounts.append(round(rng.uniform(100, 250_000), 2))
    table = pa.table(
        {
            "call_id": range(1, ROWS + 1),
            "cust_pan": pans,
            "mobile": mobiles,
            "amount": amounts,
            "notes": notes,
        }
    )
    PATH.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(table, PATH, row_group_size=20_000)
    print(f"wrote {ROWS:,} synthetic rows to {PATH}")


if __name__ == "__main__":
    main()
