"""Build the `india_places` list in spec/detectors.yaml from India Post's directory.

Source: All India Pincode Directory, Department of Posts, Government of
India, published on the Open Government Data Platform India (data.gov.in)
under the Government Open Data License - India (GODL). The list keeps the
district names and the head post office towns (towns large enough to have
a head office), cleaned, plus the current and former names of cities renamed
or formed since the directory's release.

Usage:
  python tools/build_india_places.py DIRECTORY.csv [DATE]
DIRECTORY.csv is the directory as CSV (data.gov.in, or the India Data
Platform's copy pincode_30052019.csv); DATE is its release date for the
attribution note (default: from the file name). Rewrites the block between
the BEGIN/END markers in spec/detectors.yaml; run tools/sync-spec.sh after.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

SPEC = Path(__file__).resolve().parents[1] / "spec/detectors.yaml"
BEGIN = "  # BEGIN india_places"
END = "  # END india_places"

# Current and former names of renamed or new cities, and well-known areas
# that the directory files under another district name.
ALIASES = [
    "Bengaluru",
    "Bangalore",
    "Kolkata",
    "Calcutta",
    "Mumbai",
    "Bombay",
    "Navi Mumbai",
    "Chennai",
    "Madras",
    "Gurugram",
    "Gurgaon",
    "Noida",
    "Greater Noida",
    "Delhi",
    "New Delhi",
    "Prayagraj",
    "Allahabad",
    "Mysuru",
    "Mysore",
    "Mangaluru",
    "Mangalore",
    "Belagavi",
    "Belgaum",
    "Kalaburagi",
    "Gulbarga",
    "Puducherry",
    "Pondicherry",
    "Thiruvananthapuram",
    "Trivandrum",
    "Kochi",
    "Cochin",
    "Vadodara",
    "Baroda",
    "Thane",
    "Secunderabad",
    "Ghaziabad",
    "Faridabad",
    "Visakhapatnam",
    "Vizag",
]
NAME = re.compile(r"^[A-Za-z][A-Za-z .'-]{2,40}[A-Za-z]$")


def clean(name: str) -> str | None:
    # "Hamirpur HO HP Circle" -> "Hamirpur": the town is what comes before the office type.
    office = r"\s+(?:H\.?\s?O|G\.?\s?P\.?\s?O|HPO|S\.?\s?O|B\.?\s?O)\b\.?"
    name = re.split(office, name.strip(), flags=re.I)[0]
    name = re.sub(r"\s+", " ", name.replace(".", " ")).strip()
    name = re.sub(r"(?:\s+[A-Z]{2})+$", "", name)  # a trailing state code: "Bilaspur HP"
    words = name.split(" ")
    name = " ".join(w for i, w in enumerate(words) if i == 0 or w.lower() != words[i - 1].lower())
    if not NAME.match(name):  # stray encodings, brackets, digits
        return None
    name = " ".join(w if w.isupper() and len(w) <= 3 else w.capitalize() for w in name.split(" "))
    return name if len(name) >= 4 else None  # shorter names are too ambiguous


def main() -> None:
    src = Path(sys.argv[1])
    date = sys.argv[2] if len(sys.argv) > 2 else (re.findall(r"\d{8}", src.name) or ["unknown"])[0]
    rows = list(csv.DictReader(src.open(encoding="utf-8", errors="replace")))
    key = {k.lower().replace(" ", ""): k for k in rows[0]}
    district, office, otype = key["district"], key["officename"], key["officetype"]
    places = {clean(r[district]) for r in rows}
    places |= {clean(r[office]) for r in rows if r[otype].upper() == "HO"}
    places = sorted({p for p in places if p} | set(ALIASES), key=lambda p: (-len(p), p))
    items = ", ".join("'" + p.replace("'", "''") + "'" for p in places)
    wrapped = re.sub(r"(.{1,72})(?:, |$)", r"\1,\n                  ", items).rstrip(", \n")
    block = (
        f"{BEGIN} (generated by tools/build_india_places.py; do not edit by hand)\n"
        "  # Indian districts and head post office towns, longest first, from the All\n"
        "  # India Pincode Directory, Department of Posts, Government of India,\n"
        f"  # data.gov.in, Government Open Data License - India (release {date});\n"
        "  # plus current and former names of renamed cities.\n"
        f"  india_places: [{wrapped}]\n"
        f"{END}\n"
    )
    text = SPEC.read_text(encoding="utf-8")
    if BEGIN in text:
        old = rf"{re.escape(BEGIN)}.*?{re.escape(END)}\n"
        text = re.sub(old, lambda _: block, text, flags=re.S)
    else:
        text = text.replace("\ntables:\n", "\n" + block + "\ntables:\n", 1)  # end of `lists`
    SPEC.write_text(text, encoding="utf-8")
    print(f"india_places: {len(places)} names from {len(rows)} post offices")


if __name__ == "__main__":
    main()
